#!/usr/bin/env python3
"""Coverage report for the line bank: trigger x category x roast x bond x mood, holes, opening variety.
Usage: python3 content/tools/coverage_matrix.py [lang] > content/COVERAGE.md  (default lang: en)"""
import json, sys, collections
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
lang = sys.argv[1] if len(sys.argv) > 1 else "en"
lines = [l for f in sorted((ROOT / "app/src/main/assets/lines" / lang).glob("*.json")) for l in json.load(open(f, encoding="utf-8"))]
CATS = ["SOCIAL", "VIDEO", "GAME", "MESSAGING", "SHOPPING", "BROWSER", "PRODUCTIVITY", "OTHER"]
BOND = {0: "stranger", 1: "roommate", 2: "friend", 3: "ride_or_die"}
by = collections.defaultdict(list)
for l in lines: by[l["trigger"]].append(l)
def opening(t): return " ".join(t.lower().split()[:2])
print(f"# LINE BANK COVERAGE ({lang}) — generated by content/tools/coverage_matrix.py\n\nTotal lines: {len(lines)}\n")
print("## Per trigger\n\n| trigger | lines | roast 1/2/3 | bond 0/1/2/3 | slot-free | distinct openings (2 words) | max same opening |\n|---|---|---|---|---|---|---|")
for t, ls in sorted(by.items()):
    r = [sum(x["roast"] == i for x in ls) for i in (1, 2, 3)]
    b = [sum(x.get("bondMin", 0) == i for x in ls) for i in range(4)]
    o = collections.Counter(opening(x["text"]) for x in ls)
    print(f"| {t} | {len(ls)} | {'/'.join(map(str, r))} | {'/'.join(map(str, b))} | {sum(not x.get('slots') for x in ls)} | {len(o)} | {max(o.values())} |")
holes = []
print("\n## Pause lines: category x roast (lines whose categories include the cell; empty categories = any)\n")
for t in ("PAUSE_PROMPT", "PAUSE_STAY", "PAUSE_LEAVE"):
    print(f"### {t}\n\n| category | R1 | R2 | R3 | bond>=1 |\n|---|---|---|---|---|")
    for c in CATS:
        m = [x for x in by[t] if not x["categories"] or c in x["categories"]]
        cnt = [sum(x["roast"] == i for x in m) for i in (1, 2, 3)]
        bn = sum(x.get("bondMin", 0) >= 1 for x in m)
        print(f"| {c} | {cnt[0]} | {cnt[1]} | {cnt[2]} | {bn} |")
        if t == "PAUSE_PROMPT" and c != "OTHER" and (min(cnt) < 2): holes.append(f"{t}/{c}: roast counts {cnt}")
    print()
print("## Mood coverage per trigger (lines allowing each mood; empty moods = any)\n\n| trigger | " + " | ".join(["CHILL","SLEEPY","GRUMPY","SMUG","PANICKING","IMPRESSED","SOFT"]) + " |\n|---|---|---|---|---|---|---|---|")
MOODS = ["CHILL","SLEEPY","GRUMPY","SMUG","PANICKING","IMPRESSED","SOFT"]
for t, ls in sorted(by.items()):
    row = [sum((not x["moods"]) or m in x["moods"] for x in ls) for m in MOODS]
    print(f"| {t} | " + " | ".join(map(str, row)) + " |")
    for m, n in zip(MOODS, row):
        if n < 3 and t in ("PAUSE_PROMPT","PAUSE_STAY","PAUSE_LEAVE","POKE","CALLBACK") : holes.append(f"{t}/mood {m}: {n}")
for t, ls in by.items():
    if len(ls) < 8 and t not in ("WELCOME",): holes.append(f"{t}: only {len(ls)} lines")
    if t not in ("ALMOST_CARING","WELCOME","IMPRESSED") and sum(x.get("bondMin",0)>=1 for x in ls) < 3: holes.append(f"{t}: fewer than 3 roommate+ lines")
ids = [l["id"] for l in lines]
print("\n## Holes (rule-of-thumb thresholds)\n")
print("\n".join(f"- {h}" for h in holes) if holes else "- none")
