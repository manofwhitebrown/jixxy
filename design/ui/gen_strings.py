#!/usr/bin/env python3
"""Generate app/src/main/res/values/strings.xml from content/MICROCOPY.md (WRITER-owned).

Key a.b.c -> a_b_c. Placeholders {app} {minutes} {n} {time} {permission} {brand} become positional
format args, numbered in order of appearance (sample lines: app=1, minutes=2). Keys WRITER has not
provided yet live in MANUAL below as [P] placeholders; delete each once MICROCOPY has it.
Usage: python3 design/ui/gen_strings.py
"""
import re, sys

MANUAL = {
    "home_open_weekly": "[P] Weekly review",
    "common_cancel": "[P] Cancel",
    "settings_language_value_en": "[P] English",
    "whatsaw_event_foreground": "[P] Opened",
    "whatsaw_event_session_minutes": "[P] Open for %1$d min",
    "whatsaw_event_pause_shown": "[P] Pause card shown",
    "whatsaw_event_pause_stay": "[P] You chose to stay",
    "whatsaw_event_pause_leave": "[P] You chose to leave",
    "whatsaw_event_line_shown": "[P] Jixxy said something",
    "whatsaw_event_line_reaction": "[P] You reacted to a line",
    "whatsaw_event_charger_on": "[P] Charger plugged in",
    "whatsaw_event_nap": "[P] Napped",
    "whatsaw_event_late_night_open": "[P] Late-night app open",
    "placeholder_weekly": "[P] Weekly review goes here",
    "oem_title_xiaomi": "[P] Xiaomi / Redmi / POCO",
    "oem_title_oppo": "[P] Oppo / Realme / OnePlus",
    "oem_title_vivo": "[P] Vivo / iQOO",
    "oem_title_samsung": "[P] Samsung",
    "oem_title_stock": "[P] Other phones (stock Android)",
    "oem_dontkillmyapp_note": "[P] More phone-specific help: dontkillmyapp.com (open it in your browser).",
}
PAT = re.compile(r"^\s*(?:\d+\.\s+|-\s+)`([a-z0-9_.]+)`\s+—\s+(.*)$")

def esc(t):
    return t.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

def fmt(key, text):
    if key.startswith("onboarding.roast.sample_"):
        idx = {"app": 1, "minutes": 2}
        return re.sub(r"\{(\w+)\}", lambda m: "%%%d$%s" % (idx[m.group(1)], "d" if m.group(1) == "minutes" else "s"), text)
    n = [0]
    def rep(m):
        n[0] += 1
        return "%%%d$%s" % (n[0], "d" if m.group(1) in ("n", "minutes") else "s")
    return re.sub(r"\{(\w+)\}", rep, text)

def main():
    src = open("content/MICROCOPY.md", encoding="utf-8").read()
    out, seen = [], set()
    for line in src.splitlines():
        m = PAT.match(line)
        if not m:
            continue
        name = m.group(1).replace(".", "_")
        if name in seen:
            continue
        seen.add(name)
        out.append('    <string name="%s">%s</string>' % (name, esc(fmt(m.group(1), m.group(2).strip()))))
    manual = ['    <string name="%s">%s</string>' % (k, esc(v)) for k, v in MANUAL.items() if k not in seen]
    xml = ('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
           '    <!-- GENERATED by design/ui/gen_strings.py from content/MICROCOPY.md. Do not hand-edit. -->\n'
           + "\n".join(out) + "\n    <!-- [P] placeholders: keys not yet in MICROCOPY -->\n" + "\n".join(manual) + "\n</resources>\n")
    open("app/src/main/res/values/strings.xml", "w", encoding="utf-8").write(xml)
    print(len(out), "generated,", len(manual), "placeholders")

if __name__ == "__main__":
    sys.exit(main())
